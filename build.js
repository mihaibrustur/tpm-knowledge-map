#!/usr/bin/env node
// Compiles the markdown in tpm-knowledge/ into data.js for the site. No dependencies.
//
//   tpm-knowledge/NN-<domain-id>/index.md   the domain
//   tpm-knowledge/NN-<domain-id>/<id>.md    a concept in that domain
//   tpm-knowledge/stories/<id>.md           a story
//
// Each file: optional front matter (related, author), "# Label", the summary paragraph,
// then "## " sections. Concepts: Why it matters, In practice, Pitfalls, Reflect. Stories: Prompts, Experience.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "tpm-knowledge");
const sections = {
  "Why it matters": "why",
  "In practice": "practice",
  "Pitfalls": "pitfalls",
  "Reflect": "reflect",
  "Prompts": "prompts",
  "Experience": "experience"
};
const lists = ["practice", "pitfalls", "reflect", "prompts"];

function parse(file) {
  const where = path.relative(__dirname, file);
  let text = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const meta = {};
  const fm = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (fm) {
    text = text.slice(fm[0].length);
    for (const line of fm[1].split("\n")) {
      const m = line.match(/^(\w+):\s*(.*)$/);
      if (!m) continue;
      const v = m[2].trim();
      meta[m[1]] = v.startsWith("[") ? v.slice(1, -1).split(",").map(s => s.trim()).filter(Boolean) : v;
    }
  }

  const title = text.match(/^# (.+)$/m);
  if (!title) throw new Error(where + ": missing '# Label' heading");
  const parts = text.slice(title.index + title[0].length).split(/^## /m);
  const node = { label: title[1].trim(), summary: parts[0].trim() };

  for (const part of parts.slice(1)) {
    const nl = part.indexOf("\n");
    const heading = (nl < 0 ? part : part.slice(0, nl)).trim();
    const content = nl < 0 ? "" : part.slice(nl + 1).trim();
    const key = sections[heading];
    if (!key) throw new Error(where + ": unknown section '## " + heading + "'");
    node[key] = lists.includes(key)
      ? content.split("\n").filter(l => l.startsWith("- ")).map(l => l.slice(2).trim())
      : content;
  }
  return { meta, node };
}

function make(id, type, parent, file) {
  const { meta, node } = parse(file);
  const n = { id, type };
  if (parent) n.parent = parent;
  Object.assign(n, node);
  if (meta.related) n.related = meta.related;
  if (type === "story") n.experience = n.experience || null;
  n.author = meta.author || "ai";
  return n;
}

const nodes = [];
const dirs = fs.readdirSync(root, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort();
const mdFiles = dir => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith(".md") && f !== "index.md").sort();

for (const dir of dirs.filter(d => /^\d+-/.test(d))) {
  const id = dir.replace(/^\d+-/, "");
  nodes.push(make(id, "domain", null, path.join(root, dir, "index.md")));
  for (const f of mdFiles(dir)) nodes.push(make(f.slice(0, -3), "concept", id, path.join(root, dir, f)));
}
if (dirs.includes("stories")) {
  for (const f of mdFiles("stories")) nodes.push(make(f.slice(0, -3), "story", null, path.join(root, "stories", f)));
}

const ids = new Set();
for (const n of nodes) {
  if (ids.has(n.id)) throw new Error("duplicate id: " + n.id);
  ids.add(n.id);
}
for (const n of nodes) {
  for (const r of n.related || []) if (!ids.has(r)) console.warn("warning: " + n.id + " links to unknown id " + r);
}

const header = "// Generated by build.js from tpm-knowledge/. Edit the markdown, then run: node build.js\n";
fs.writeFileSync(path.join(__dirname, "data.js"), header + "window.TPM_DATA = " + JSON.stringify({ nodes }, null, 2) + ";\n");
console.log("Wrote data.js: " + nodes.length + " nodes.");
